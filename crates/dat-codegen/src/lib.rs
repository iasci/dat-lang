//! Emits Rust from the typed IR.
//!
//! One Rust function per dat function, no macros, and every runtime-checked
//! operation calls dat-rt with a `&'static Loc`. Runtime errors unwind; a
//! `try` block becomes a closure run by `dat_rt::catch`, and `return`,
//! `break` and `continue` leave it as a `dat_rt::Flow` value. Every function
//! takes its caller's `dat_rt::Frame` record and the call's location as its
//! last two arguments, and builds its own record from them; a throw walks the
//! records to build a dat-only trace.

#![forbid(unsafe_code)]

pub mod build;

use dat_ir::{self as ir, ExprKind, Stmt, Type};
use std::collections::HashMap;
use std::fmt::Write as _;

/// What the generated program does when it starts.
pub enum Entry {
    /// Run `main` of the first program.
    Run,
    /// Run the tests of every program. The binary takes `--filter` and `--verbose`.
    Test,
}

/// Emits one crate's `main.rs` for the given programs.
pub fn emit_crate(programs: &[&ir::Program], entry: &Entry) -> String {
    let mut out = String::new();
    let files: Vec<&str> = programs.iter().map(|p| p.file.as_str()).collect();
    let _ = writeln!(out, "// Generated by dat from {}. Do not edit.", files.join(", "));
    out.push_str(
        "#![forbid(unsafe_code)]\n\
         #![deny(warnings)]\n\
         #![allow(dead_code, unused_mut, unused_variables, unused_assignments, unused_labels, unreachable_code, unused_parens, unused_braces)]\n\
         #![allow(non_snake_case, unconditional_recursion)]\n\
         #![allow(clippy::all)]\n",
    );
    for (i, p) in programs.iter().enumerate() {
        out.push('\n');
        out.push_str(&emit_program(i, p, matches!(entry, Entry::Test)));
    }
    out.push_str("\nfn main() {\n");
    match entry {
        Entry::Run => {
            let main = programs[0].main.expect("checked: run needs main");
            let _ = writeln!(out, "    dat_rt::run_main(p0::{})", fn_name(programs[0], main));
        }
        Entry::Test => {
            out.push_str("    let tests: &[dat_rt::testing::CompiledTest] = &[\n");
            for (i, p) in programs.iter().enumerate() {
                for t in &p.tests {
                    let f = p.func(t.func);
                    let _ = writeln!(
                        out,
                        "        dat_rt::testing::CompiledTest {{ name: {:?}, frame: {:?}, loc: dat_rt::Loc {{ file: p{i}::FILE, func: {:?}, line: {}, col: {} }}, run: p{i}::{} }},",
                        t.name,
                        f.name,
                        f.name,
                        t.loc.line,
                        t.loc.col,
                        fn_name(p, t.func)
                    );
                }
            }
            out.push_str("    ];\n    dat_rt::testing::main(tests)\n");
        }
    }
    out.push_str("}\n");
    out
}

fn fn_name(p: &ir::Program, id: ir::FuncId) -> String {
    let f = p.func(id);
    let clean: String = f.name.chars().map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_lowercase() } else { '_' }).collect();
    let clean = clean.trim_matches('_').to_string();
    let clean: String = clean.split('_').filter(|s| !s.is_empty()).collect::<Vec<_>>().join("_");
    format!("f{}_{}", id.0, clean)
}

/// `DAT_NO_STACK_GUARD=1` leaves the stack check out, only so a benchmark
/// can measure what the guard costs.
pub fn no_stack_guard() -> bool {
    std::env::var_os("DAT_NO_STACK_GUARD").is_some_and(|v| v == "1")
}

fn rust_type(t: Type) -> &'static str {
    match t {
        Type::Int => "i64",
        Type::Bool => "bool",
        Type::Str => "dat_rt::Str",
        Type::Void => "()",
        Type::Never => "!",
        Type::Error(_) => "dat_rt::DatError",
    }
}

fn is_copy(t: Type) -> bool {
    matches!(t, Type::Int | Type::Bool | Type::Void)
}

/// Tests are left out unless the crate runs them, as in production builds.
fn emit_program(index: usize, p: &ir::Program, with_tests: bool) -> String {
    let mut g = Gen { p, locs: HashMap::new(), loc_order: Vec::new(), func: String::new() };
    let mut funcs = String::new();
    for (i, f) in p.functions.iter().enumerate() {
        if !with_tests && p.tests.iter().any(|t| t.func.0 as usize == i) {
            continue;
        }
        funcs.push('\n');
        funcs.push_str(&g.function(ir::FuncId(i as u32), f));
    }
    let mut out = String::new();
    let _ = writeln!(out, "mod p{index} {{\n    pub const FILE: &str = {:?};", p.file);
    for (i, l) in g.loc_order.iter().enumerate() {
        let _ = writeln!(
            out,
            "    static L{i}: dat_rt::Loc = dat_rt::Loc {{ file: FILE, func: {:?}, line: {}, col: {} }};",
            l.1, l.0.line, l.0.col
        );
    }
    for line in funcs.lines() {
        if line.is_empty() {
            out.push('\n');
        } else {
            let _ = writeln!(out, "    {line}");
        }
    }
    out.push_str("}\n");
    out
}

struct Gen<'p> {
    p: &'p ir::Program,
    locs: HashMap<(u32, u32), usize>,
    /// Each location and the dat function it's in.
    loc_order: Vec<(ir::Loc, String)>,
    /// The dat function being emitted.
    func: String,
}

/// Where `return`, `break` and `continue` go from the code being emitted.
#[derive(Clone, Copy)]
struct Ctx {
    /// Inside a `try` closure: they leave it as a `Flow` value.
    in_closure: bool,
    /// The innermost loop that is reachable without leaving the closure, and
    /// whether it has a step (so `continue` breaks out of the body block).
    lp: Option<(u32, bool)>,
    /// Some loop encloses this code, possibly outside the closure.
    any_loop: bool,
}

impl<'p> Gen<'p> {
    fn loc(&mut self, l: ir::Loc) -> String {
        let n = self.locs.len();
        let i = *self.locs.entry((l.line, l.col)).or_insert_with(|| {
            self.loc_order.push((l, self.func.clone()));
            n
        });
        format!("&L{i}")
    }

    fn local(&self, f: &ir::Function, l: ir::LocalId) -> String {
        let name = &f.locals[l.0 as usize].name;
        let clean: String = name.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' }).collect();
        format!("l{}_{}", l.0, clean)
    }

    fn function(&mut self, id: ir::FuncId, f: &ir::Function) -> String {
        self.func = f.name.clone();
        let mut params: Vec<String> =
            (0..f.params).map(|i| format!("{}: {}", self.local(f, ir::LocalId(i)), rust_type(f.locals[i as usize].ty))).collect();
        params.push("__up: &dat_rt::Frame<'_>".to_string());
        params.push("__at: Option<&'static dat_rt::Loc>".to_string());
        let ret = match f.ret {
            Type::Void => String::new(),
            t => format!(" -> {}", rust_type(t)),
        };
        let mut s = String::new();
        let _ = writeln!(s, "pub fn {}({}){ret} {{", fn_name(self.p, id), params.join(", "));
        if f.recursive && !no_stack_guard() {
            s.push_str("    dat_rt::stack_check(__up, __at);\n");
        }
        s.push_str("    let __f = &dat_rt::Frame { parent: Some(__up), at: __at };\n");
        let ctx = Ctx { in_closure: false, lp: None, any_loop: false };
        let mut loops = 0;
        let body = self.block(f, &f.body, ctx, 1, &mut loops);
        s.push_str(&body);
        if f.ret != Type::Void {
            s.push_str("    dat_rt::unreachable()\n");
        }
        s.push_str("}\n");
        s
    }

    fn block(&mut self, f: &ir::Function, b: &[Stmt], ctx: Ctx, depth: usize, loops: &mut u32) -> String {
        let mut out = String::new();
        for s in b {
            self.stmt(f, s, ctx, depth, loops, &mut out);
        }
        out
    }

    fn stmt(&mut self, f: &ir::Function, s: &Stmt, ctx: Ctx, depth: usize, loops: &mut u32, out: &mut String) {
        let ind = "    ".repeat(depth);
        match s {
            Stmt::Let(l, e) => {
                let local = &f.locals[l.0 as usize];
                let m = if local.reassigned { "mut " } else { "" };
                let v = self.expr(f, e);
                let _ = writeln!(out, "{ind}let {m}{}: {} = {v};", self.local(f, *l), rust_type(local.ty));
            }
            Stmt::Set(l, e) => {
                let v = self.expr(f, e);
                let _ = writeln!(out, "{ind}{} = {v};", self.local(f, *l));
            }
            Stmt::Expr(e) => {
                // A discarded value: `let _ =` keeps rustc's unused-value lints quiet.
                let v = self.expr(f, e);
                if matches!(e.ty, Type::Void | Type::Never) {
                    let _ = writeln!(out, "{ind}{v};");
                } else {
                    let _ = writeln!(out, "{ind}let _ = {v};");
                }
            }
            Stmt::If(c, t, e) => {
                let c = self.expr(f, c);
                let _ = writeln!(out, "{ind}if {c} {{");
                out.push_str(&self.block(f, t, ctx, depth + 1, loops));
                if e.is_empty() {
                    let _ = writeln!(out, "{ind}}}");
                } else {
                    let _ = writeln!(out, "{ind}}} else {{");
                    out.push_str(&self.block(f, e, ctx, depth + 1, loops));
                    let _ = writeln!(out, "{ind}}}");
                }
            }
            Stmt::Loop { cond, body, step } => {
                *loops += 1;
                let id = *loops;
                let inner = Ctx { in_closure: ctx.in_closure, lp: Some((id, !step.is_empty())), any_loop: true };
                let _ = writeln!(out, "{ind}'l{id}: loop {{");
                if let Some(c) = cond {
                    let c = self.expr(f, c);
                    let _ = writeln!(out, "{ind}    if !{c} {{\n{ind}        break 'l{id};\n{ind}    }}");
                }
                if step.is_empty() {
                    out.push_str(&self.block(f, body, inner, depth + 1, loops));
                } else {
                    let _ = writeln!(out, "{ind}    'c{id}: {{");
                    out.push_str(&self.block(f, body, inner, depth + 2, loops));
                    let _ = writeln!(out, "{ind}    }}");
                    out.push_str(&self.block(f, step, inner, depth + 1, loops));
                }
                let _ = writeln!(out, "{ind}}}");
            }
            Stmt::Break => {
                let _ = writeln!(out, "{ind}{}", self.break_code(ctx));
            }
            Stmt::Continue => {
                let _ = writeln!(out, "{ind}{}", self.continue_code(ctx));
            }
            Stmt::Return(e) => {
                let v = e.as_ref().map(|e| self.expr(f, e));
                let code = self.return_code(ctx, v.as_deref());
                let _ = writeln!(out, "{ind}{code}");
            }
            Stmt::Throw(e, loc) => {
                let v = self.expr(f, e);
                let l = self.loc(*loc);
                let _ = writeln!(out, "{ind}dat_rt::throw_new({v}, {l}, __f);");
            }
            Stmt::Try { body, catches } => self.try_stmt(f, body, catches, ctx, depth, loops, out),
        }
    }

    fn return_code(&self, ctx: Ctx, v: Option<&str>) -> String {
        match (ctx.in_closure, v) {
            (true, Some(v)) => format!("return dat_rt::Flow::Return({v});"),
            (true, None) => "return dat_rt::Flow::Return(());".to_string(),
            (false, Some(v)) => format!("return {v};"),
            (false, None) => "return;".to_string(),
        }
    }

    fn break_code(&self, ctx: Ctx) -> String {
        match ctx.lp {
            Some((id, _)) => format!("break 'l{id};"),
            None if ctx.in_closure && ctx.any_loop => "return dat_rt::Flow::Break;".to_string(),
            None => "dat_rt::unreachable();".to_string(),
        }
    }

    fn continue_code(&self, ctx: Ctx) -> String {
        match ctx.lp {
            Some((id, true)) => format!("break 'c{id};"),
            Some((id, false)) => format!("continue 'l{id};"),
            None if ctx.in_closure && ctx.any_loop => "return dat_rt::Flow::Continue;".to_string(),
            None => "dat_rt::unreachable();".to_string(),
        }
    }

    #[allow(clippy::too_many_arguments)]
    fn try_stmt(
        &mut self,
        f: &ir::Function,
        body: &[Stmt],
        catches: &[ir::Catch],
        ctx: Ctx,
        depth: usize,
        loops: &mut u32,
        out: &mut String,
    ) {
        let ind = "    ".repeat(depth);
        let ret = match f.ret {
            Type::Never => "()",
            t => rust_type(t),
        };
        let inner = Ctx { in_closure: true, lp: None, any_loop: ctx.any_loop };
        let _ = writeln!(out, "{ind}match dat_rt::catch(|| -> dat_rt::Flow<{ret}> {{");
        out.push_str(&self.block(f, body, inner, depth + 1, loops));
        let _ = writeln!(out, "{ind}    dat_rt::Flow::Normal");
        let _ = writeln!(out, "{ind}}}) {{");
        let _ = writeln!(out, "{ind}    Ok(dat_rt::Flow::Normal) => {{}}");
        // A `never` function can't return, so its try blocks never give `Return`.
        let on_return = match f.ret {
            Type::Never => "dat_rt::unreachable()".to_string(),
            Type::Void => self.return_code(ctx, None),
            _ => self.return_code(ctx, Some("__v")),
        };
        let _ = writeln!(out, "{ind}    Ok(dat_rt::Flow::Return(__v)) => {{ {on_return} }}");
        let _ = writeln!(out, "{ind}    Ok(dat_rt::Flow::Break) => {{ {} }}", self.break_code(ctx));
        let _ = writeln!(out, "{ind}    Ok(dat_rt::Flow::Continue) => {{ {} }}", self.continue_code(ctx));
        let _ = writeln!(out, "{ind}    Err(__e) => {{");
        let mut has_catch_all = false;
        for (i, c) in catches.iter().enumerate() {
            let cond = match c.filter {
                ir::CatchFilter::Is(t) => format!("__e.kind == dat_rt::ErrorKind::{}", t.name()),
                _ => {
                    has_catch_all = true;
                    "true".to_string()
                }
            };
            let kw = if i == 0 { "if" } else { "} else if" };
            let _ = writeln!(out, "{ind}        {kw} {cond} {{");
            if let Some(b) = c.bind {
                let value = if c.filter == ir::CatchFilter::AllAsError { "(*__e).into_error()" } else { "*__e" };
                let _ = writeln!(out, "{ind}            let {}: dat_rt::DatError = {value};", self.local(f, b));
            }
            out.push_str(&self.block(f, &c.body, ctx, depth + 3, loops));
            if has_catch_all {
                break;
            }
        }
        if !has_catch_all {
            let _ = writeln!(out, "{ind}        }} else {{\n{ind}            dat_rt::rethrow(__e);");
        }
        let _ = writeln!(out, "{ind}        }}");
        let _ = writeln!(out, "{ind}    }}");
        let _ = writeln!(out, "{ind}}}");
    }

    fn expr(&mut self, f: &ir::Function, e: &ir::Expr) -> String {
        match &e.kind {
            ExprKind::Int(n) if *n < 0 => format!("({n}i64)"),
            ExprKind::Int(n) => format!("{n}i64"),
            ExprKind::Bool(b) => b.to_string(),
            ExprKind::Str(s) => format!("dat_rt::Str::new({s:?})"),
            ExprKind::Local(l) => {
                let name = self.local(f, *l);
                if is_copy(e.ty) { name } else { format!("{name}.clone()") }
            }
            ExprKind::Call { func, args, loc } => {
                let l = self.loc(*loc);
                let mut vals: Vec<String> = args.iter().map(|a| self.expr(f, a)).collect();
                vals.push("__f".to_string());
                vals.push(format!("Some({l})"));
                format!("{}({})", fn_name(self.p, *func), vals.join(", "))
            }
            ExprKind::IntArith { op, lhs, rhs, loc } => {
                let name = match op {
                    ir::IntOp::Add => "add",
                    ir::IntOp::Sub => "sub",
                    ir::IntOp::Mul => "mul",
                    ir::IntOp::Rem => "rem",
                };
                let (a, b) = (self.expr(f, lhs), self.expr(f, rhs));
                let l = self.loc(*loc);
                format!("dat_rt::int::{name}({a}, {b}, {l}, __f)")
            }
            ExprKind::IntNeg { arg, loc } => {
                let a = self.expr(f, arg);
                let l = self.loc(*loc);
                format!("dat_rt::int::neg({a}, {l}, __f)")
            }
            ExprKind::Compare { op, lhs, rhs } => {
                let (a, b) = (self.expr(f, lhs), self.expr(f, rhs));
                format!("({a} {} {b})", op.symbol())
            }
            ExprKind::Not(a) => format!("(!{})", self.expr(f, a)),
            ExprKind::And(a, b) => format!("({} && {})", self.expr(f, a), self.expr(f, b)),
            ExprKind::Or(a, b) => format!("({} || {})", self.expr(f, a), self.expr(f, b)),
            ExprKind::Cond { cond, then, els } => {
                format!("(if {} {{ {} }} else {{ {} }})", self.expr(f, cond), self.expr(f, then), self.expr(f, els))
            }
            ExprKind::Concat(parts) => {
                let parts: Vec<String> = parts.iter().map(|p| format!("{}.as_str()", self.expr(f, p))).collect();
                format!("dat_rt::Str::concat(&[{}])", parts.join(", "))
            }
            ExprKind::ToStr(a) => {
                let v = self.expr(f, a);
                match a.ty {
                    Type::Int => format!("dat_rt::int_to_str({v})"),
                    Type::Bool => format!("dat_rt::bool_to_str({v})"),
                    Type::Error(_) => format!("{v}.to_str()"),
                    _ => v,
                }
            }
            ExprKind::NewError { kind, message } => {
                let m = self.expr(f, message);
                format!("dat_rt::DatError::new(dat_rt::ErrorKind::{}, {m}.as_str())", kind_name(*kind))
            }
            ExprKind::ErrorMessage(a) => format!("{}.message_str()", self.expr(f, a)),
            ExprKind::Print(a) => format!("dat_rt::print({})", self.expr(f, a)),
            ExprKind::Assert(a) => self.assert(f, a),
            ExprKind::Diverge(a) => {
                let v = self.expr(f, a);
                format!("{{ let __n: {} = {v}; __n }}", rust_type(e.ty))
            }
            ExprKind::Fail { message, loc } => {
                let m = self.expr(f, message);
                let l = self.loc(*loc);
                format!("dat_rt::fail({m}, {l}, __f)")
            }
        }
    }

    fn assert(&mut self, f: &ir::Function, a: &ir::Assert) -> String {
        let l = self.loc(a.loc);
        let mut s = String::from("{ ");
        let (cond, sides) = match &a.cond {
            ir::AssertCond::Plain(c) => {
                let v = self.expr(f, c);
                let _ = write!(s, "let __c: bool = {v}; ");
                ("__c".to_string(), "None".to_string())
            }
            ir::AssertCond::Compare { op, lhs, rhs } => {
                let (x, y) = (self.expr(f, lhs), self.expr(f, rhs));
                let _ = write!(s, "let __l = {x}; let __r = {y}; ");
                let debug = |v: &str| match lhs.ty {
                    Type::Int => format!("dat_rt::debug_int({v})"),
                    Type::Bool => format!("dat_rt::debug_bool({v})"),
                    _ => format!("dat_rt::debug_str({v}.as_str())"),
                };
                (format!("(__l {} __r)", op.symbol()), format!("Some(({}, {}))", debug("__l"), debug("__r")))
            }
        };
        let msg = match &a.message {
            Some(m) => {
                let v = self.expr(f, m);
                let _ = write!(s, "let __m: dat_rt::Str = {v}; ");
                "Some(__m)".to_string()
            }
            None => "None".to_string(),
        };
        let _ = write!(s, "if !{cond} {{ dat_rt::assert_failed({:?}, {:?}, {sides}, {msg}, {l}, __f) }} }}", a.src, a.cond_src);
        s
    }
}

fn kind_name(t: ir::ErrorType) -> &'static str {
    match t {
        ir::ErrorType::Any => "Error",
        other => other.name(),
    }
}
